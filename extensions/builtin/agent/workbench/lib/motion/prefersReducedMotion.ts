// Reduced motion is checked at reveal time instead of being read once at
// module load, so a user changing the OS setting does not need to restart the
// editor before the transcript stops animating.
export function prefersReducedMotion() {
  return (
    typeof window !== "undefined" &&
    window.matchMedia?.("(prefers-reduced-motion: reduce)").matches === true
  );
}
